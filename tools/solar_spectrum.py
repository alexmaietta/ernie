"""Writes ernie/util/solar_table.h, the Sun's spectral irradiance at
1 au that Ernie embeds, from the TSIS-1 Hybrid Solar Reference
Spectrum (HSRS) version 2 full spectrum extension (CC BY 4.0, LASP).

Download its 1 nm binned CSV from LISIRD's LaTiS server, then run:

    curl -o tsis1_hsrs_binned_fs.csv \\
        https://lasp.colorado.edu/lisird/latis/dap/tsis1_hsrs_binned_fs.csv
    python tools/solar_spectrum.py tsis1_hsrs_binned_fs.csv \\
        ernie/util/solar_table.h

The table keeps the 1 nm bins from 115.5 to 2729.5 nm and averages
the rest, out to 200 um, over bins 1% wide in wavelength, which keep
the total to well under 0.1% while the thermal infrared's smooth
spectrum needs no finer sampling. Each value is its bin's mean, at
the bin's centre.

References:
- O. M. Coddington et al., "The TSIS-1 Hybrid Solar Reference
  Spectrum", Geophysical Research Letters 48(12):e2020GL091709, 2021.
  https://doi.org/10.1029/2020GL091709
- O. M. Coddington et al., "Version 2 of the TSIS-1 Hybrid Solar
  Reference Spectrum and Extension to the Full Spectrum", Earth and
  Space Science 10(3):e2022EA002637, 2023.
  https://doi.org/10.1029/2022EA002637
"""

import csv
import sys

FINE_END_NM = 2730.0
COARSE_RATIO = 1.01


def read(path):
    with open(path, newline="") as file:
        rows = list(csv.reader(file))[1:]
    return [(float(r[0]), float(r[1])) for r in rows]


def reduce(samples):
    fine = [(w, e) for w, e in samples if w < FINE_END_NM]
    coarse = [(w, e) for w, e in samples if w >= FINE_END_NM]
    out = list(fine)
    low = FINE_END_NM
    i = 0
    while i < len(coarse):
        high = low * COARSE_RATIO
        values = []
        while i < len(coarse) and coarse[i][0] < high:
            values.append(coarse[i][1])
            i += 1
        if values:
            # The source's 1 nm bins cover [low, high) whole.
            end = coarse[i - 1][0] + 0.5
            out.append((0.5 * (low + end), sum(values) / len(values)))
            low = end
    return out


def write(table, path, total):
    lines = [
        "// SPDX-License-Identifier: BSD-3-Clause",
        "// Generated by tools/solar_spectrum.py; do not edit.",
        "//",
        "// The Sun's spectral irradiance at 1 au, W m^-2 nm^-1, from the",
        "// TSIS-1 Hybrid Solar Reference Spectrum version 2, full spectrum",
        "// extension (LASP, CC BY 4.0; Coddington et al. 2021, 2023):",
        "// 1 nm bins to 2730 nm, then bins 1% wide to 200 um, each its",
        "// bin's mean at the bin's centre.",
        f"// Total: {total:.4f} W/m^2.",
        "#pragma once",
        "",
        "namespace ernie::solar_table {",
        "",
        f"inline constexpr int kCount = {len(table)};",
        "",
        "/// (nm, W m^-2 nm^-1) pairs.",
        "// clang-format off",
        f"inline constexpr double kPairs[{2 * len(table)}] = {{",
    ]
    for w, e in table:
        lines.append(f"    {w:.6g}, {e:.7g},")
    lines += [
        "};",
        "// clang-format on",
        "",
        "}  // namespace ernie::solar_table",
        "",
    ]
    with open(path, "w") as file:
        file.write("\n".join(lines))


def main():
    source, target = sys.argv[1], sys.argv[2]
    samples = read(source)
    total = sum(e for _, e in samples)  # 1 nm bins
    table = reduce(samples)
    write(table, target, total)
    print(
        f"{len(table)} samples, total {total:.4f} W/m^2 -> {target}"
    )


if __name__ == "__main__":
    main()
