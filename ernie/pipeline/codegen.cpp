std::string NodeType(const NodeDef& def, const ResolvedNode& node) {
    if (def.uniforms.empty()) {
        return def.type;
    }
    std::string arguments;
    for (uint32_t index = 0; index < def.uniforms.size(); ++index) {
        const std::vector<std::string>& allowed = def.uniforms[index].allowed;
        const auto found = std::ranges::find(allowed, node.uniforms[index]);
        arguments += std::format("{}{}", index == 0 ? "" : ", ",
                                 found == allowed.end() ? 0 : found - allowed.begin());
    }
    return std::format("{}<{}>", def.type, arguments);
}

