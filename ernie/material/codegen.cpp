uint64_t Mix(uint64_t hash, std::string_view bytes) {
    for (const char byte : bytes) {
        hash = (hash ^ uint8_t(byte)) * 0x100000001b3ull;
    }
    return hash;
}

std::string Cases(const MaterialDefinitionSet& set, std::string_view standard,
                  std::string_view surface) {
    std::string cases;
    for (const MaterialDefinition& definition : set.Definitions()) {
        const std::string_view call = definition.surface ? surface : standard;
        cases +=
            std::format("    }} else if (context.definition == {}) {{\n        {}\n", definition.id,
                        std::vformat(call, std::make_format_args(definition.type)));
    }
    return cases;
}

std::string Dispatch(const MaterialDefinitionSet& set) {
    std::string imports;
    std::string linked;
    for (const MaterialDefinition& definition : set.Definitions()) {
        imports += std::format("import {};\n", definition.module);
        linked += std::format(" || definition == {}", definition.id);
    }
    return std::format(
        R"(// SPDX-License-Identifier: BSD-3-Clause
// Generated by ernie/material/codegen.cpp; do not edit.

__exported import ernie.render.kernels.material.definitions.diffuse;
__exported import ernie.render.kernels.material.definitions.preview;
{}
using namespace ernie;

bool Linked(uint definition) {{
    return definition < {}{};
}}

void Choose(inout ShadeContext context) {{
    if (Linked(context.definition)) {{
        return;
    }}
    const MaterialRecord record = context.materials.Record(context.material);
    if (Linked(record.previousDefinition)) {{
        context.definition = record.previousDefinition;
        context.words = record.previousWords;
    }} else {{
        context.definition = kDefinitionPlaceholder;
    }}
}}

void ShadeDefinition<Spectrum : ISpectrum>(inout ShadeContext context,
                                           inout OpticalClosure<Spectrum> closure) {{
    Choose(context);
    if (context.definition == kDefinitionPreviewTextured ||
            context.definition == kDefinitionPreviewConstant) {{
        StandardDefinition<PreviewMaterial, Spectrum>.Shade(context, closure);
{}    }} else {{
        StandardDefinition<DiffuseMaterial, Spectrum>.Shade(context, closure);
    }}
}}

Spectrum AlbedoDefinition<Spectrum : ISpectrum>(inout ShadeContext context) {{
    Choose(context);
    if (context.definition == kDefinitionPreviewTextured ||
            context.definition == kDefinitionPreviewConstant) {{
        return StandardDefinition<PreviewMaterial, Spectrum>.Albedo(context);
{}    }} else {{
        return StandardDefinition<DiffuseMaterial, Spectrum>.Albedo(context);
    }}
}}
)",
        imports, kFirstGeneratedDefinition, linked,
        Cases(set, "StandardDefinition<{}, Spectrum>.Shade(context, closure);",
              "{}<Spectrum>.Shade(context, closure);"),
        Cases(set, "return StandardDefinition<{}, Spectrum>.Albedo(context);",
              "return {}<Spectrum>.Albedo(context);"));
}

std::string_view CellType(MaterialInputType type) {
    switch (type) {
    case MaterialInputType::Bool:
        return "uint";
    case MaterialInputType::Int:
        return "int";
    case MaterialInputType::Float:
        return "float";
    case MaterialInputType::Float2:
        return "Float2";
    case MaterialInputType::Float3:
        return "Float3";
    case MaterialInputType::Float4:
        return "Float4";
    case MaterialInputType::Spectral:
        return "Float3";
    }
    return "float";
}

std::string_view SlangType(MaterialInputType type) {
    switch (type) {
    case MaterialInputType::Bool:
        return "bool";
    case MaterialInputType::Int:
        return "int";
    case MaterialInputType::Float:
        return "float";
    case MaterialInputType::Float2:
        return "float2";
    case MaterialInputType::Float3:
        return "float3";
    case MaterialInputType::Float4:
        return "float4";
    case MaterialInputType::Spectral:
        return "SpectralValue";
    }
    return "float";
}

std::string Expression(const ShadingGraph& graph, const GraphLayout& layout, uint32_t node,
                       uint32_t input) {
    const InputBinding& binding = graph.nodes[node].inputs[input];
    const MaterialNodeInput& declared = graph.nodes[node].node->inputs[input];
    const bool spectral = declared.type == MaterialInputType::Spectral;
    if (binding.kind == BindingKind::Pattern) {
        return spectral ? std::format("SpectralValue.Rgb(r{})", binding.source)
                        : std::format("r{}", binding.source);
    }
    const std::string cell = std::format("p.n{}_{}", node, declared.name);
    if (binding.kind == BindingKind::Texture) {
        const std::string sampled =
            std::format("texels.texels[{0}], texels.Handle({0}), &p.textures[{0}]",
                        layout.textures[node][input]);
        if (declared.type == MaterialInputType::Float) {
            return std::format("TexturedFloat({}, {})", cell, sampled);
        }
        const std::string color = std::format("TexturedColor({}, {})", cell, sampled);
        return spectral ? std::format("SpectralValue.Rgb({})", color) : color;
    }
    if (spectral) {
        return std::format("({0}_spectrum != kNoSpectrum ? SpectralValue.Library({0}_spectrum) : "
                           "SpectralValue.Rgb({0}.Vector()))",
                           cell);
    }
    switch (declared.type) {
    case MaterialInputType::Bool:
        return cell + " != 0";
    case MaterialInputType::Float2:
    case MaterialInputType::Float3:
    case MaterialInputType::Float4:
        return cell + ".Vector()";
    default:
        return cell;
    }
}

std::string Call(const ShadingGraph& graph, const GraphLayout& layout, uint32_t node) {
    const MaterialNodeDefinition& definition = *graph.nodes[node].node;
    std::string arguments;
    for (const MaterialNodeParameter& parameter : definition.parameters) {
        arguments += arguments.empty() ? "" : ", ";
        switch (parameter.source) {
        case MaterialNodeParameter::Source::Context:
            arguments += "context";
            break;
        case MaterialNodeParameter::Source::Point:
            arguments += "context.point";
            break;
        case MaterialNodeParameter::Source::Input:
            arguments += Expression(graph, layout, node, parameter.input);
            break;
        }
    }
    return std::format("        const {} r{} = {}({});\n", SlangType(definition.result), node,
                       definition.name, arguments);
}

