std::string Cases(const DefinitionSet& set, std::string_view call) {
    std::string cases;
    for (const DefinitionModule& definition : set.Definitions()) {
        cases +=
            std::format("    }} else if (context.definition == {}) {{\n        {}\n", definition.id,
                        std::vformat(call, std::make_format_args(definition.type)));
    }
    return cases;
}

std::string Dispatch(const DefinitionSet& set) {
    std::string imports;
    std::string linked;
    for (const DefinitionModule& definition : set.Definitions()) {
        imports += std::format("import {};\n", definition.module);
        linked += std::format(" || definition == {}", definition.id);
    }
    return std::format(
        R"(// SPDX-License-Identifier: BSD-3-Clause
// Generated by ernie/material/codegen.cpp; do not edit.

__exported import ernie.render.kernels.material.definitions.diffuse;
__exported import ernie.render.kernels.material.definitions.preview;
{}
using namespace ernie;

bool Linked(uint definition) {{
    return definition < {}{};
}}

void Choose(inout ShadeContext context) {{
    if (Linked(context.definition)) {{
        return;
    }}
    const MaterialRecord record = context.materials.Record(context.material);
    if (Linked(record.previousDefinition)) {{
        context.definition = record.previousDefinition;
        context.words = record.previousWords;
    }} else {{
        context.definition = kDefinitionPlaceholder;
    }}
}}

void ShadeDefinition<Spectrum : ISpectrum>(inout ShadeContext context,
                                           inout OpticalClosure<Spectrum> closure) {{
    Choose(context);
    if (context.definition == kDefinitionPreviewTextured ||
            context.definition == kDefinitionPreviewConstant) {{
        StandardDefinition<PreviewMaterial, Spectrum>.Shade(context, closure);
{}    }} else {{
        StandardDefinition<DiffuseMaterial, Spectrum>.Shade(context, closure);
    }}
}}

Spectrum AlbedoDefinition<Spectrum : ISpectrum>(inout ShadeContext context) {{
    Choose(context);
    if (context.definition == kDefinitionPreviewTextured ||
            context.definition == kDefinitionPreviewConstant) {{
        return StandardDefinition<PreviewMaterial, Spectrum>.Albedo(context);
{}    }} else {{
        return StandardDefinition<DiffuseMaterial, Spectrum>.Albedo(context);
    }}
}}
)",
        imports, kFirstGeneratedDefinition, linked,
        Cases(set, "StandardDefinition<{}, Spectrum>.Shade(context, closure);"),
        Cases(set, "return StandardDefinition<{}, Spectrum>.Albedo(context);"));
}

std::string ModuleFile(std::string_view module) {
    std::string file(module);
    for (char& c : file) {
        c = c == '.' ? '/' : c;
    }
    return file + ".slang";
}

std::string_view CellType(NodeInputType type) {
    switch (type) {
    case NodeInputType::Bool:
        return "uint";
    case NodeInputType::Int:
        return "int";
    case NodeInputType::Float:
        return "float";
    case NodeInputType::Float2:
        return "Float2";
    case NodeInputType::Float3:
        return "Float3";
    case NodeInputType::Float4:
        return "Float4";
    }
    return "float";
}

std::string Assignment(const NodeInput& input, uint32_t texture) {
    const std::string cell = std::format("p.{}", input.name);
    if (texture != kNoTexture) {
        const std::string sampled =
            std::format("texels.texels[{0}], texels.Handle({0}), &p.textures[{0}]", texture);
        return input.type == NodeInputType::Float
                   ? std::format("TexturedFloat({}, {})", cell, sampled)
                   : std::format("TexturedColor({}, {})", cell, sampled);
    }
    switch (input.type) {
    case NodeInputType::Bool:
        return cell + " != 0";
    case NodeInputType::Float2:
    case NodeInputType::Float3:
    case NodeInputType::Float4:
        return cell + ".Vector()";
    default:
        return cell;
    }
}

